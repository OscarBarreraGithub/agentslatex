CREATE TABLE IF NOT EXISTS sessions (
 id TEXT PRIMARY KEY, user_id INTEGER NOT NULL, login TEXT NOT NULL,
 token TEXT NOT NULL, expires INTEGER NOT NULL, refresh_lock INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS oauth_states (id TEXT PRIMARY KEY, verifier TEXT NOT NULL, expires INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS projects (
 repo_id INTEGER PRIMARY KEY, owner TEXT NOT NULL, name TEXT NOT NULL,
 branch TEXT NOT NULL, main TEXT NOT NULL, engine TEXT NOT NULL DEFAULT 'pdf', created INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS creations (
 user_id INTEGER NOT NULL, request_id TEXT NOT NULL, name TEXT NOT NULL,
 repo_id INTEGER, created INTEGER NOT NULL, PRIMARY KEY(user_id,request_id)
);
